const fs = require('fs');
const path = require('path');

const loadRoute = (routePath, routeName) => {
  try {
    const fullPath = path.resolve(__dirname, routePath);
    const route = require(fullPath);
    if (route && typeof route === 'function') {
      console.log(`✅ ${routeName} - Loaded successfully`);
      return true;
    }
    console.log(`⚠️  ${routeName} - Invalid export (Path: ${routePath})`);
    return false;
  } catch (e) {
    console.log(`❌ ${routeName} - Error/Not found: ${e.message} (Path: ${routePath})`);
    return false;
  }
};

